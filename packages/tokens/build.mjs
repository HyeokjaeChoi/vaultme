// Style Dictionary build: packages/tokens/tokens.json -> src/generated/*.ts
// Dark = the `semanticDark` set (Tokens Studio theme "Dark") layered over `semantic`; component values follow by alias.
// Source is Tokens Studio style ({ value, type }, `{path}` aliases without layer prefix). SD v5 reads that natively,
// so sd-transforms is not needed. A preprocessor adds the layer prefix to every alias so layers stay separate.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import StyleDictionary from 'style-dictionary'

const root = `${import.meta.dirname}/`
const foundation = resolve(root, 'tokens.json')
const out = `${root}src/generated/`
const ESC = '__value'
const LAYERS = ['primitive', 'semantic', 'component']

const isToken = (o) => o && typeof o === 'object' && 'value' in o && 'type' in o
const has = (tree, path) =>
  path.split('.').reduce((n, k) => (n && typeof n === 'object' ? n[k] : undefined), tree) !== undefined

function qualify(tree) {
  const fix = (v) =>
    typeof v === 'string'
      ? v.replace(/\{([^}]+)\}/g, (_, p) => {
          const hits = LAYERS.filter((l) => isToken(tree[l]?.[p.split('.')[0]]) || has(tree[l] ?? {}, p))
          if (hits.length !== 1) throw new Error(`alias {${p}} matches layers: ${hits.join(',') || 'none'}`)
          return `{${hits[0]}.${p}}`
        })
      : v && typeof v === 'object'
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fix(x)]))
        : v
  // A group child named `value` would make SD treat the group as a token. Escape the key, restore it in the format.
  const key = (k) => (k === 'value' ? ESC : k)
  const walk = (o) =>
    !o || typeof o !== 'object'
      ? o
      : isToken(o)
        ? { ...o, value: fix(o.value) }
        : Object.fromEntries(Object.entries(o).map(([k, v]) => [key(k), walk(v)]))
  return walk(tree)
}

const px = (s) => (typeof s === 'string' && s.endsWith('px') ? Number.parseFloat(s) : s)
const WEIGHT = { regular: '400', medium: '500', 'semi bold': '600', bold: '700' }
const pct = (s) => (typeof s === 'string' && s.endsWith('%') ? Number.parseFloat(s) / 100 : undefined)

function convert(type, v) {
  switch (type) {
    case 'spacing':
    case 'sizing':
    case 'borderRadius':
    case 'borderWidth':
    case 'dimension':
    case 'fontSizes':
      return px(v)
    case 'fontWeights':
      return WEIGHT[String(v).toLowerCase()] ?? String(v)
    case 'lineHeights':
      return px(v)
    case 'typography': {
      const size = px(v.fontSize)
      const lh = pct(v.lineHeight)
      const ls = pct(v.letterSpacing)
      return {
        fontFamily: v.fontFamily,
        fontWeight: convert('fontWeights', v.fontWeight),
        fontSize: size,
        lineHeight: lh ? Math.round(size * lh) : px(v.lineHeight),
        letterSpacing: ls ? Math.round(size * ls * 100) / 100 : 0,
      }
    }
    case 'boxShadow':
      return {
        shadowColor: v.color,
        shadowOffset: { width: px(v.x), height: px(v.y) },
        shadowRadius: px(v.blur) / 2,
        shadowOpacity: 1,
      }
    case 'other': {
      const m = /^cubic-bezier\(([^)]+)\)$/.exec(v)
      return m ? m[1].split(',').map(Number) : v
    }
    default:
      return v
  }
}

StyleDictionary.registerPreprocessor({ name: 'vaultme/qualify', preprocessor: qualify })
StyleDictionary.registerFormat({
  name: 'vaultme/ts',
  format: ({ dictionary, options }) => {
    const tree = {}
    for (const t of dictionary.allTokens) {
      const path = t.path.map((k) => (k === ESC ? 'value' : k))
      if (path[0] === 'primitive' && ['font'].includes(path[1])) continue // composite font source, not for apps. primitive.type (display, heading) is emitted for app screens (S01, S40, S60)
      let n = tree
      for (const k of path.slice(0, -1)) n = n[k] ??= {}
      n[path.at(-1)] = convert(t.type, t.value)
    }
    return `// GENERATED by packages/tokens/build.mjs. Do not edit.\nexport const ${options.exportName} = ${JSON.stringify(tree, null, 2)} as const\n`
  },
})

mkdirSync(out, { recursive: true })
const src = JSON.parse(readFileSync(foundation, 'utf8'))
const layers = { primitive: src.primitive, semantic: src.semantic, component: src.component }
const merge = (a, b) =>
  Object.fromEntries(
    [...new Set([...Object.keys(a), ...Object.keys(b)])].map((k) => [
      k,
      k in b ? (isToken(b[k]) || !(k in a) ? b[k] : merge(a[k], b[k])) : a[k],
    ]),
  )
const themes = { light: layers, dark: { ...layers, semantic: merge(layers.semantic, src.semanticDark) } }

for (const [name, tokens] of Object.entries(themes)) {
  const sd = new StyleDictionary({
    tokens,
    log: { verbosity: 'silent', warnings: 'error' },
    preprocessors: ['vaultme/qualify'],
    platforms: {
      rn: {
        transforms: ['name/kebab'],
        buildPath: out,
        files: [{ destination: `${name}.ts`, format: 'vaultme/ts', options: { exportName: name } }],
      },
    },
  })
  await sd.buildAllPlatforms()
}
writeFileSync(
  `${out}tokens.ts`,
  `// GENERATED\nimport { light } from './light'\nimport { dark } from './dark'\n\nexport { light, dark }\ntype Widen<T> = T extends '100' | '200' | '300' | '400' | '500' | '600' | '700' | '800' | '900' ? T : T extends string ? string : T extends number ? number : { readonly [K in keyof T]: Widen<T[K]> }\nexport type Theme = Widen<typeof light>\n`,
)

// ---- CSS: tokens.css (custom properties) and theme.css (Tailwind v4 @theme) ----
// Names are `--<layer>-<path>` in kebab-case. Primitive holds raw values; Semantic and Component are var() aliases, so a theme
// switch only re-declares the Semantic variables that dark changes. Composite tokens split into one variable per field
// (typography) or join into one value (boxShadow). The two themes come from the same SD run as the TS output.
const kebab = (s) =>
  s
    .replace(/_/g, '-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
const cssName = (path, part) => `--${[...path, ...(part ? [part] : [])].map(kebab).join('-')}`
const tokenPath = (t) => t.path.map((k) => (k === ESC ? 'value' : k))
const aliasOf = (v) => (typeof v === 'string' ? /^\{([^}]+)\}$/.exec(v)?.[1] : undefined)
const em = (s) => (typeof s === 'string' && s.endsWith('%') ? `${+(Number.parseFloat(s) / 100).toFixed(4)}em` : s)
const TYPE_FIELDS = {
  fontFamily: 'fontFamilies',
  fontWeight: 'fontWeights',
  fontSize: 'fontSizes',
  lineHeight: 'lineHeights',
  letterSpacing: 'letterSpacing',
}
const SHADOW_FIELDS = ['x', 'y', 'blur', 'spread', 'color']

function cssRaw(type, v) {
  switch (type) {
    case 'fontFamilies':
      return JSON.stringify(v)
    case 'fontWeights':
      return WEIGHT[String(v).toLowerCase()] ?? String(v)
    case 'letterSpacing':
      return em(v)
    default:
      return String(v)
  }
}

// [name, value] pairs of one token. `original.value` still holds the (layer-qualified) alias, so aliases stay var() references.
function cssDecls(t, byPath) {
  const name = cssName(tokenPath(t))
  const o = t.original.value
  const ref = (p) => `var(${cssName(p.split('.'))})`
  const target = aliasOf(o)
  if (target) {
    const kind = byPath.get(target)?.type
    return kind === 'typography'
      ? Object.keys(TYPE_FIELDS).map((f) => [cssName(tokenPath(t), f), `var(${cssName(target.split('.'), f)})`])
      : [[name, ref(target)]]
  }
  if (t.type === 'typography')
    return Object.entries(TYPE_FIELDS).map(([f, type]) => [
      cssName(tokenPath(t), f),
      aliasOf(o[f]) ? ref(aliasOf(o[f])) : cssRaw(type, o[f]),
    ])
  if (t.type === 'boxShadow')
    return [[name, SHADOW_FIELDS.map((f) => (aliasOf(o[f]) ? ref(aliasOf(o[f])) : o[f])).join(' ')]]
  return [[name, cssRaw(t.type, o)]]
}

async function cssTheme(tokens) {
  const sd = new StyleDictionary({
    tokens,
    log: { verbosity: 'silent', warnings: 'error' },
    preprocessors: ['vaultme/qualify'],
    platforms: { css: { transforms: [] } },
  })
  const { allTokens } = await sd.getPlatformTokens('css')
  const byPath = new Map(allTokens.map((t) => [tokenPath(t).join('.'), t]))
  const vars = new Map()
  for (const t of allTokens)
    for (const [n, v] of cssDecls(t, byPath)) {
      if (vars.has(n)) throw new Error(`css variable ${n} is declared twice`)
      vars.set(n, v)
    }
  return { allTokens, vars }
}

const lines = (entries) => entries.map(([n, v]) => `  ${n}: ${v};`).join('\n')
const cssLight = await cssTheme(themes.light)
const cssDark = await cssTheme(themes.dark)
const darkOnly = [...cssDark.vars].filter(([n, v]) => cssLight.vars.get(n) !== v)
if (darkOnly.some(([n]) => !n.startsWith('--semantic-'))) throw new Error('dark may only change Semantic variables')
const HEADER = '/* GENERATED by packages/tokens/build.mjs from tokens.json. Do not edit. */'
writeFileSync(
  `${out}tokens.css`,
  `${HEADER}\n:root {\n  color-scheme: light;\n${lines([...cssLight.vars])}\n}\n\n` +
    `/* Dark follows the system unless the page sets data-theme="light". */\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${lines(darkOnly).replace(/^/gm, '  ')}\n  }\n}\n\n` +
    `:root[data-theme="dark"] {\n  color-scheme: dark;\n${lines(darkOnly)}\n}\n`,
)

// Tailwind v4: `--*: initial` clears every default (palette, spacing, radius, type scale, ...). Then only tokens are mapped.
// `inline` keeps the var() reference in each utility, so utilities follow the light/dark switch of tokens.css.
// Namespaces: https://tailwindcss.com/docs/theme#theme-variable-namespaces. Primitive colors are not mapped (use Semantic).
// Breakpoints and container sizes are the one place with literal values (resolved from the same tokens): CSS media and container queries cannot read var().
// Not mappable: border widths and opacity (no theme namespace), font family of a text style (use font-*).
const NAMESPACE = {
  color: 'color',
  spacing: 'spacing',
  sizing: 'spacing',
  borderRadius: 'radius',
  fontSizes: 'text',
  typography: 'text',
  fontFamilies: 'font',
  fontWeights: 'font-weight',
  letterSpacing: 'tracking',
  lineHeights: 'leading',
  boxShadow: 'shadow',
}
// Leading path segments dropped from Primitive names (`primitive.space.4` -> `--spacing-4`), and Semantic group names that repeat the namespace.
const STRIP = {
  primitive: [
    'space',
    'radius',
    'elevation',
    'breakpoint',
    'type',
    'size',
    'font.family',
    'font.weight',
    'font.size',
    'font.lineHeight',
    'font.tracking',
    'motion.easing',
  ],
  semantic: ['typography', 'shape'],
  component: [],
}
const twName = (t) => {
  const [layer, ...rest] = tokenPath(t)
  const strip = STRIP[layer].find((s) => rest.join('.').startsWith(`${s}.`) && s.split('.').length < rest.length)
  return rest
    .slice(strip ? strip.split('.').length : 0)
    .map(kebab)
    .join('-')
}
const theme = new Map()
const tw = (n, v, layer) => {
  // A Component token that re-aliases the Semantic token of the same name (iconSize.*) maps once, to Semantic.
  if (theme.has(n) && layer !== 'component') throw new Error(`tailwind variable ${n} is declared twice`)
  if (!theme.has(n)) theme.set(n, v)
}
for (const t of cssLight.allTokens) {
  const [layer, group] = tokenPath(t)
  const breakpoint = layer === 'primitive' && group === 'breakpoint'
  const ns =
    t.type === 'dimension'
      ? breakpoint
        ? 'breakpoint'
        : 'container'
      : t.type === 'other' && group === 'motion'
        ? 'ease'
        : NAMESPACE[t.type]
  if (!ns || (layer === 'primitive' && (t.type === 'color' || group === 'grid'))) continue // grid: Figma layout source, Semantic layout.* aliases it
  const name = `--${ns}-${twName(t)}`
  const varName = cssName(tokenPath(t))
  // Semantic layout.breakpoint.* (web desktop 1280, product desktop 1200) also become Tailwind breakpoints (`web-desktop:` variant).
  if (layer === 'semantic' && t.type === 'dimension' && tokenPath(t).slice(1, 3).join('.') === 'layout.breakpoint')
    tw(`--breakpoint-${kebab(tokenPath(t).at(-1))}`, t.value, layer)
  if (t.type === 'typography') {
    tw(name, `var(${varName}-font-size)`, layer)
    for (const part of ['lineHeight', 'letterSpacing', 'fontWeight'])
      tw(`${name}--${kebab(part)}`, `var(${varName}-${kebab(part)})`, layer)
  } else if (t.type === 'dimension')
    tw(name, t.value, layer) // media and container queries cannot read var(), so Tailwind needs the literal value
  else tw(name, `var(${varName})`, layer)
}
writeFileSync(
  `${out}theme.css`,
  `${HEADER}\n/* Use after \`@import "tailwindcss"\` and tokens.css. */\n@theme inline {\n  --*: initial;\n${lines([...theme])}\n}\n`,
)
